vim.opt.rtp:prepend(vim.fn.getcwd())
local plugin = require("format_tools")
local options = { default_format_opts = { timeout_ms = 321 } }
local caller = vim.deepcopy(options)
plugin.setup(options)
assert(vim.deep_equal(caller, options), "setup mutated caller configuration")
local commands = vim.api.nvim_get_commands({})
local handlers = vim.api.nvim_get_autocmds({})
assert(not pcall(plugin.setup, false), "setup(false) must reject an invalid configuration type")
assert(vim.deep_equal(commands, vim.api.nvim_get_commands({})), "Invalid setup replaced commands")
assert(vim.deep_equal(handlers, vim.api.nvim_get_autocmds({})), "Invalid setup replaced handlers")
plugin.setup(caller)
assert(#vim.api.nvim_get_autocmds({}) == #handlers, "Repeated setup duplicated automatic handlers")
print("format-tools.nvim: setup input isolation, invalid configuration and registration lifetime passed")

local configured = plugin.config()
options.default_format_opts.timeout_ms = 999
assert(plugin.config().default_format_opts.timeout_ms == configured.default_format_opts.timeout_ms)
assert(not pcall(plugin.setup, { max_output = -1 }))
assert(vim.deep_equal(configured, plugin.config()))
plugin.disable()
plugin.enable()
assert(plugin.config().default_format_opts.timeout_ms == 321)
vim.api.nvim_create_user_command("FormatToolsInfo", function() end, { desc = "personal formatter command" })
plugin.dispose()
plugin.dispose()
assert(plugin.config() == nil and plugin.status() == nil and not plugin.is_enabled())
assert(vim.fn.exists("#FormatTools") == 0)
assert(vim.api.nvim_get_commands({}).FormatToolsInfo)
vim.api.nvim_del_user_command("FormatToolsInfo")
plugin.enable()
assert(plugin.config().default_format_opts.timeout_ms == 1000)
plugin.dispose()
